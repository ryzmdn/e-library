CREATE TABLE IF NOT EXISTS membership_tiers (
    id TINYINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    tier_code VARCHAR(30) NOT NULL UNIQUE,
    tier_name VARCHAR(60) NOT NULL,
    max_physical_loans TINYINT UNSIGNED NOT NULL DEFAULT 3,
    loan_duration_days TINYINT UNSIGNED NOT NULL DEFAULT 7,
    max_renewals TINYINT UNSIGNED NOT NULL DEFAULT 1,
    daily_fine_amount DECIMAL(10, 2) NOT NULL DEFAULT 1000.00,
    max_fine_cap DECIMAL(10, 2) NOT NULL DEFAULT 50000.00,
    can_access_restricted_thesis BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
