CREATE TABLE IF NOT EXISTS loan_transactions (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    transaction_code VARCHAR(36) NOT NULL UNIQUE,
    idempotency_key VARCHAR(64) NOT NULL UNIQUE,
    user_id BIGINT UNSIGNED NOT NULL,
    book_copy_id BIGINT UNSIGNED NOT NULL,
    issued_by_staff_id BIGINT UNSIGNED NOT NULL,
    returned_to_staff_id BIGINT UNSIGNED DEFAULT NULL,
    borrowed_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    due_date DATE NOT NULL,
    returned_at DATETIME DEFAULT NULL,
    renewal_count TINYINT UNSIGNED NOT NULL DEFAULT 0,
    loan_status ENUM('ACTIVE', 'OVERDUE', 'RETURNED', 'LOST_REPORTED') NOT NULL DEFAULT 'ACTIVE',
    return_condition ENUM('EXCELLENT', 'GOOD', 'WORN', 'DAMAGED', 'LOST') DEFAULT NULL,
    accrued_fine DECIMAL(10, 2) NOT NULL DEFAULT 0.00,
    fine_settled BOOLEAN NOT NULL DEFAULT TRUE,
    remarks VARCHAR(255) DEFAULT NULL,
    CONSTRAINT fk_loans_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE RESTRICT,
    CONSTRAINT fk_loans_copy FOREIGN KEY (book_copy_id) REFERENCES book_copies(id) ON DELETE RESTRICT,
    CONSTRAINT fk_loans_staff_out FOREIGN KEY (issued_by_staff_id) REFERENCES users(id),
    CONSTRAINT fk_loans_staff_in FOREIGN KEY (returned_to_staff_id) REFERENCES users(id),
    INDEX idx_loans_user_active (user_id, loan_status),
    INDEX idx_loans_due_status (due_date, loan_status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
