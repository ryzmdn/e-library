CREATE TABLE IF NOT EXISTS bibliographic_items (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    slug VARCHAR(220) NOT NULL UNIQUE,
    isbn_13 VARCHAR(17) DEFAULT NULL UNIQUE,
    issn VARCHAR(15) DEFAULT NULL,
    ddc_code VARCHAR(20) NOT NULL,
    call_number_base VARCHAR(50) NOT NULL,
    title VARCHAR(255) NOT NULL,
    subtitle VARCHAR(255) DEFAULT NULL,
    authors_text VARCHAR(500) NOT NULL,
    publisher_name VARCHAR(150) NOT NULL,
    publication_year SMALLINT UNSIGNED NOT NULL,
    edition_statement VARCHAR(60) DEFAULT NULL,
    language_code CHAR(5) NOT NULL DEFAULT 'id-ID',
    physical_pages SMALLINT UNSIGNED DEFAULT NULL,
    synopsis TEXT NOT NULL,
    subject_tags VARCHAR(500) NOT NULL,
    media_type ENUM('PHYSICAL_ONLY', 'DIGITAL_ONLY', 'HYBRID', 'THESIS_REPOSITORY') NOT NULL DEFAULT 'PHYSICAL_ONLY',
    cover_image_path VARCHAR(255) DEFAULT NULL,
    total_physical_copies INT UNSIGNED NOT NULL DEFAULT 0,
    available_physical_copies INT UNSIGNED NOT NULL DEFAULT 0,
    rating_avg DECIMAL(3, 2) NOT NULL DEFAULT 0.00,
    rating_count INT UNSIGNED NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    FULLTEXT INDEX ft_catalog_search (title, authors_text, subject_tags, synopsis),
    INDEX idx_catalog_filter (media_type, ddc_code, publication_year, available_physical_copies)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
