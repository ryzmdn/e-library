CREATE TABLE IF NOT EXISTS users (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    member_number VARCHAR(32) NOT NULL UNIQUE,
    email VARCHAR(190) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    full_name VARCHAR(150) NOT NULL,
    phone_number VARCHAR(25) DEFAULT NULL,
    role ENUM('SUPER_ADMIN', 'LIBRARIAN', 'CATALOGER', 'MEMBER') NOT NULL DEFAULT 'MEMBER',
    tier_id TINYINT UNSIGNED NOT NULL,
    account_status ENUM('PENDING_VERIFICATION', 'ACTIVE', 'SUSPENDED', 'GRADUATED_CLEAR') NOT NULL DEFAULT 'PENDING_VERIFICATION',
    theme_preference ENUM('LIGHT', 'DARK', 'SEPIA') NOT NULL DEFAULT 'LIGHT',
    font_scale_percent TINYINT UNSIGNED NOT NULL DEFAULT 100,
    failed_login_attempts TINYINT UNSIGNED NOT NULL DEFAULT 0,
    locked_until TIMESTAMP NULL DEFAULT NULL,
    membership_expires_at DATE NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    CONSTRAINT fk_users_tier FOREIGN KEY (tier_id) REFERENCES membership_tiers(id) ON UPDATE CASCADE,
    INDEX idx_users_status_role (account_status, role)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
